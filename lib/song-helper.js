  function suggestFallback(label, sectionText, otherText) {
    var name = String(label || 'this part').replace(/\s+/g, ' ').trim() || 'this part';
    var raw = (String(sectionText || '') + ' ' + String(otherText || '')).replace(/\s+/g, ' ').trim();
    var quoted = raw.match(/"([^"]{2,80})"/);
    var place = raw.match(/\b(?:in|at|on) the ([A-Za-z][A-Za-z']{1,24})/);
    var options = [];
    if (quoted) options.push('You said "' + quoted[1].trim() + '".');
    if (place) options.push('I was still in the ' + place[1].trim() + '.');
    if (/hook/i.test(name)) options.push('Sing this line back to me.');
    else if (/bridge/i.test(name)) options.push('This is where it turns.');
    else if (/outro/i.test(name)) options.push('Leave the light on when you go.');
    else options.push('Here is what happened next.');
    options.push('I kept the part I could not say out loud.');
    options.push('That is the picture I still see.');
    var seen = {};
    var out = [];
    options.forEach(function (line) {
      var key = line.toLowerCase();
      if (seen[key] || out.length >= 3) return;
      seen[key] = true;
      out.push(line);
    });
    return out;
  }

