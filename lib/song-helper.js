  function tidyAsk(text, sourceText, opts) {
    var options = opts || {};
    var plan = askPlan(sourceText, { lastAngle: options.lastAngle || '', asked: options.asked || [] });
    var wanted = options.angle || plan.angle;
    var q = String(text || '').replace(/\u2014/g, ',').replace(/\u2013/g, ',').replace(/\s+/g, ' ').trim();
    if (/suno/i.test(q)) q = q.replace(/suno/ig, '').replace(/\s+/g, ' ').trim();
    var askedKeys = (options.asked || []).map(askKey);
    var purpose = /\b(supposed to|meant to|here to make)\b/i.test(q);
    var bad = !q || q.length > 180 || purpose || sensoryTrivia(q, sourceText) || askAngle(q) !== wanted || askedKeys.indexOf(askKey(q)) !== -1;
    if (bad) return plan.question;
    if (q.charAt(q.length - 1) !== '?') q += '?';
    return q;
  }

