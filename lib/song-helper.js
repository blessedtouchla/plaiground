  function rhymifyFallback(label, sectionText) {
    var raw = String(sectionText || '').replace(/\s+/g, ' ').trim();
    var first = raw.split('\n')[0] || raw;
    if (first.length > 90) first = first.slice(0, 90).replace(/\s+\S*$/, '');
    var words = first.toLowerCase().match(/[a-z']+/g) || [];
    var last = words.length ? words[words.length - 1] : '';
    var pairs = [
      ['night', 'light'], ['chair', 'there'], ['you', 'too'], ['me', 'free'],
      ['stay', 'way'], ['go', 'know'], ['home', 'alone'], ['heart', 'apart'],
      ['time', 'mine'], ['day', 'stay'], ['door', 'more'], ['hand', 'stand'],
    ];
    var rhyme = 'again';
    pairs.forEach(function (pair) {
      if (pair[0] === last) rhyme = pair[1];
      else if (pair[1] === last) rhyme = pair[0];
    });
    var seed = first || ('This is the ' + (String(label || 'part').replace(/\s+/g, ' ').trim() || 'part'));
    return seed + '\nI hold it close, then say it ' + rhyme + '.';
  }

