  function usableStoryLine(text, interview) {
    var value = String(text || '').replace(/\s+/g, ' ').trim();
    if (!value || isPlaceholderLyric(value) || dropMetaLine(value, interview)) return '';
    if (value.length < 12 || value.indexOf(' ') === -1) return '';
    return value;
  }

  function hasRealStory(interview) {
    return storyCandidates(interview).some(function (bit) { return !!usableStoryLine(bit, interview); });
  }

  function firstRealHook(interview) {
    var found = '';
    storyCandidates(interview).some(function (bit) {
      var next = usableStoryLine(bit, interview);
      if (!next) return false;
      found = next;
      return true;
    });
    return found;
  }

  function missingAnswers(interview) {
    var src = interview || {};
    if (isPlaceholderLyric(src.line) || isPlaceholderLyric(src.happened) || isPlaceholderLyric(src.why)) {
      return 'Those lines are placeholders. Answer in your own words, then the hook can be written.';
    }
    var flow = flowApi();
    var northReady = !!(flow && flow.readyForDraft(src.north || {}));
    if (hasRealStory(src)) {
      if (northReady) return '';
      var line = String(src.line || '').trim();
      if (!usableStoryLine(line, src) && dropMetaLine(line, src) && (usableStoryLine(src.happened, src) || usableStoryLine(src.why, src))) {
        return '';
      }
      if (line.length < 12 || line.indexOf(' ') === -1) return 'Write the hook sentence before generating.';
      if (String(src.happened || '').trim().length < 8) return 'Say what happened before generating.';
      if (String(src.why || '').trim().length < 8) return 'Say why it matters before generating.';
      return '';
    }
    if (northReady || dropMetaLine(src.line, src) || dropMetaLine(src.happened, src) || dropMetaLine(src.why, src)) {
      return 'Tell a little more of the story. The hook needs a real detail from you, not the aim.';
    }
    var bare = String(src.line || '').trim();
    if (bare.length < 12 || bare.indexOf(' ') === -1) return 'Write the hook sentence before generating.';
    if (String(src.happened || '').trim().length < 8) return 'Say what happened before generating.';
    if (String(src.why || '').trim().length < 8) return 'Say why it matters before generating.';
    return '';
  }

