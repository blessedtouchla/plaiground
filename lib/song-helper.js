  function createLimiter(opts) {
    var windowMs = (opts && opts.windowMs) || RATE_WINDOW_MS;
    var max = (opts && opts.max) || RATE_MAX;
    var buckets = new Map();
    return {
      allow: function (ip, now) {
        var t = typeof now === 'number' ? now : Date.now();
        var key = String(ip || 'unknown');
        var prev = (buckets.get(key) || []).filter(function (ts) { return t - ts < windowMs; });
        if (prev.length >= max) {
          buckets.set(key, prev);
          return false;
        }
        prev.push(t);
        buckets.set(key, prev);
        return true;
      },
    };
  }

  function songCopyText(parts) {
    var seen = {};
    var chunks = [];
    (parts || []).forEach(function (part) {
      var text = String(part && part.text || '').replace(/\r\n/g, '\n').trim();
      if (!text) return;
      var key = text.replace(/\s+/g, ' ').toLowerCase();
      if (seen[key]) return;
      seen[key] = true;
      var label = String(part && part.label || '').replace(/\s+/g, ' ').trim();
      chunks.push(label ? (label + '\n' + text) : text);
    });
    return chunks.join('\n\n').slice(0, 12000);
  }

