  function splitAffix(token) {
    var match = String(token).match(/^([^\p{L}\p{N}]*)(.*?)([^\p{L}\p{N}]*)$/u);
    if (!match) return { lead: '', core: String(token), tail: '' };
    return { lead: match[1], core: match[2], tail: match[3] };
  }

  function caseCore(core, index, cores, atLineStart) {
    if (!core) return core;
    if (/\d/.test(core)) return core;
    var lower = core.toLowerCase();
    if (PROPER_CASE[lower]) return PROPER_CASE[lower];
    var prev = index > 0 ? String(cores[index - 1] || '').toLowerCase() : '';
    if (lower === 'x' && prev === 'tesla') return 'X';
    var next = cores[index + 1] ? String(cores[index + 1]).toLowerCase() : '';
    if (PLACE_LEAD[lower] && PLACE_WORD[next]) return PLACE_LEAD[lower];
    if (atLineStart && index === 0) return lower.charAt(0).toUpperCase() + lower.slice(1);
    return lower;
  }

  function casePhrase(phrase, atLineStart) {
    var tokens = String(phrase).split(/(\s+)/);
    var cores = [];
    tokens.forEach(function (token) {
      if (!token || /^\s+$/.test(token)) return;
      cores.push(splitAffix(token).core);
    });
    var wordIndex = 0;
    return tokens.map(function (token) {
      if (!token || /^\s+$/.test(token)) return token;
      var parts = splitAffix(token);
      var cased = caseCore(parts.core, wordIndex, cores, atLineStart);
      wordIndex += 1;
      return parts.lead + cased + parts.tail;
    }).join('');
  }

  function phraseStartsLine(text, index) {
    return !/[\p{L}\p{N}]/u.test(String(text || '').slice(0, index));
  }

  function restyleUserPhrases(line, answers) {
    var text = String(line || '');
    if (!text.trim() || !answers.length) return text;
    var ranges = [];
    answers.forEach(function (phrase) {
      var bit = String(phrase || '').trim();
      if (!bit) return;
      var re = new RegExp('(?:^|[^\\p{L}\\p{N}])(' + escapeRegExp(bit) + ')(?![\\p{L}\\p{N}])', 'giu');
      var match;
      while ((match = re.exec(text))) {
        var start = match.index + match[0].length - match[1].length;
        var end = start + match[1].length;
        var overlaps = ranges.some(function (range) {
          return start < range.end && end > range.start;
        });
        if (!overlaps) ranges.push({ start: start, end: end });
        if (match.index === re.lastIndex) re.lastIndex += 1;
      }
    });
    ranges.sort(function (a, b) { return b.start - a.start; });
    ranges.forEach(function (range) {
      var styled = casePhrase(text.slice(range.start, range.end), phraseStartsLine(text, range.start));
      text = text.slice(0, range.start) + styled + text.slice(range.end);
    });
    return text;
  }

  function normalizeWovenCasing(draft, interview) {
    var verbatim = {};
    verbatimUserItems(interview).forEach(function (item) { verbatim[item.text] = true; });
    var answers = wordBankAnswers(interview).slice().sort(function (a, b) {
      return b.length - a.length;
    });
    function fix(line) {
      var trimmed = String(line && line.text || '').trim();
      if (!trimmed || verbatim[trimmed]) return;
      line.text = restyleUserPhrases(line.text, answers);
    }
    (draft.hooks || []).forEach(fix);
    (draft.sections || []).forEach(function (sectionItem) {
      (sectionItem.lines || []).forEach(fix);
    });
  }

  function isShortWordBankLine(text, interview) {
    var value = String(text || '').trim();
    if (!value || wordCount(value) > 3) return false;
    return wordBankAnswers(interview).some(function (answer) {
      return answer.toLowerCase() === value.toLowerCase();
    });
  }

  function hasWordBankDump(draft, interview) {
    return (draft.sections || []).some(function (sectionItem) {
      var run = 0;
      var hit = false;
      (sectionItem.lines || []).forEach(function (line) {
        if (hit) return;
        if (isShortWordBankLine(line && line.text, interview)) {
          run += 1;
          if (run >= 3) hit = true;
        } else {
          run = 0;
        }
      });
      return hit;
    });
  }

  function chorusLacksTwoLines(draft) {
    return (draft.sections || []).some(function (sectionItem) {
      if (!/^chorus\b/i.test(String(sectionItem.label || '').trim())) return false;
      var seen = {};
      (sectionItem.lines || []).forEach(function (line) {
        var key = String(line && line.text || '').trim().toLowerCase();
        if (key) seen[key] = true;
      });
      return Object.keys(seen).length < 2;
    });
  }

  function verseTooThin(draft) {
    return (draft.sections || []).some(function (sectionItem) {
      if (!/^verse\b/i.test(String(sectionItem.label || '').trim())) return false;
      return lyricLineCount(sectionItem) < MIN_VERSE_LINES;
    });
  }

  function draftNeedsRetry(draft, interview) {
    return hasWordBankDump(draft, interview) || chorusLacksTwoLines(draft) || verseTooThin(draft);
  }

