'use strict';
const assert = require('assert');
const SM = require('./slang-mode.js');
const A = require('./arcade.js');
const data = require('../data/slang.json');
const bay = data.entries.filter((e) => e.region_tag === 'Bay Area');
assert.ok(bay.length >= 5, 'bay entries');
bay.forEach((e) => {
  assert.ok(Array.isArray(e.sources) && e.sources.every((u) => /^https:\/\//.test(u)) && (e.sources.length || e.source_note), e.word + ' needs a source or source note');
  assert.ok(e.define && e.example, e.word + ' needs define + example');
  assert.ok(!/\u2014|\u2013/.test(e.define + e.example + e.meaning), 'no em dashes');
});
assert.ok(!data.entries.some((e) => /ghost ?rid/i.test(e.word)), 'ghost ride skipped');
assert.ok(bay.find((e) => e.word === 'thizz').explicit === true, 'thizz flagged explicit');
assert.strictEqual(data.count, data.entries.length);

const m = SM.matcher(data.entries, 'Bay Area');
const parts = SM.findTerms('We went dumb on the turf, hella hyphy tonight', m);
assert.deepStrictEqual(parts.filter((p) => p.entry).map((p) => p.text), ['went dumb', 'turf', 'hella', 'hyphy']);
assert.strictEqual(parts.map((p) => p.text).join(''), 'We went dumb on the turf, hella hyphy tonight', 'text round-trips');
assert.strictEqual(SM.findTerms('hellacious shellac', m).filter((p) => p.entry).length, 0, 'whole words only');
assert.strictEqual(SM.findTerms('Thizzin all night', m)[0].entry.word, 'thizz');
const pop = SM.popover(bay.find((e) => e.word === 'hella'));
assert.ok(pop.define.length < 140 && pop.example, 'short popover');

const st = { card: 'flip', flip: { slang: 'bay', target: 'Hip hop' }, answers: {} };
const fp = A.flipPrompt('[Verse]\nline', st);
assert.ok(/Hyphy mode/.test(fp) && /hella/.test(fp) && !/thizz/i.test(fp), 'clean mode skips drug words');
const ex = A.flipPrompt('[Verse]\nline', Object.assign({}, st, { explicit: 'ok', ageOk: true, flip: { slang: 'bay', vibe: 'dirty', level: 'Spicy' } }));
assert.ok(/thizz/.test(ex), 'explicit mode may use thizz');
assert.ok(!/thizz/i.test(A.scrubOutput('[Verse]\nall thizzin tonight\nhella good', st)), 'thizz removed when not explicit');
const sp = A.stylePrompt(st, { genre: 'Hip hop' });
assert.ok(!/hella|go dumb|fetti|yadadamean/i.test(sp), 'slang words never in the style prompt: ' + sp);
assert.ok(/hyphy bounce/.test(sp) && /synth bass/.test(sp), 'hyphy sound kit in the style prompt (Both badge): ' + sp);
const little = A.stylePrompt({ card: 'flip', flip: { slang: 'bay', hyphy: 'little', target: 'Hip hop' }, answers: {} }, { genre: 'Hip hop' });
assert.ok(/subtle Bay bounce/.test(little) && !/heavy synth bass/.test(little), 'A little stays subtle');
const dumbSt = { card: 'flip', flip: { slang: 'bay', hyphy: 'dumb', target: 'Hip hop' }, answers: {} };
const dumb = A.stylePrompt(dumbSt, { genre: 'Hip hop' });
const bpm = Number((dumb.match(/(\d+) BPM/) || [])[1]);
assert.ok(/hand claps/.test(dumb) && /chant-rap/.test(dumb) && bpm >= 100 && bpm <= 110, 'Go dumb: full kit at 100 to 110 BPM: ' + dumb);
const fus = A.flipStyle({ card: 'flip', flip: { slang: 'bay', hyphy: 'dumb', fusionOn: true, fusion: ['Hip hop', 'Reggae'] }, answers: {} }, { fusion: ['Hip hop', 'Reggae'] });
assert.ok(fus.style.length <= 200 && /hyphy bounce/.test(fus.style) && fus.ok, 'fusion keeps rules: ' + fus.style + JSON.stringify(fus.warnings));
assert.ok(/boom bap|skank|dub/.test(fus.style), 'fusion keeps both genres');
assert.strictEqual(SM.nextLevel('little'), 'hyphy'); assert.strictEqual(SM.nextLevel('dumb'), 'dumb');
assert.ok(/\[Hype Break\]/.test(SM.lyricRule('bay', false, 'hyphy')) && /last rhyme word/.test(SM.lyricRule('bay', false, 'dumb')));
assert.ok(/keep every line/.test(A.flipPrompt('x', { card: 'flip', flip: { slang: 'bay', hyphy: 'dumb', boost: true }, answers: {} })), 'Go more hyphy keeps meaning and rhymes');
assert.ok(data.entries.filter((e) => e.region_tag === 'Bay Area').length >= 30, '30+ Bay words');
['slizzard', 'bammer'].forEach((w) => assert.ok(data.entries.find((e) => e.word === w).explicit, w + ' explicit'));
assert.ok(!/who asked/.test(A.sampleFlip('[Verse]\nline one here', st)), 'bay sample');
console.log('slang mode tests passed');
