'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const read = (rel) => fs.readFileSync(path.join(__dirname, '..', rel), 'utf8');

const js = read('site.js');
const css = read('site.css');
assert.ok(js.includes('function appendSideGroup'), 'every side group is expandable');
assert.ok(js.includes('function wireSideAccordion'), 'headers share one accordion');
['My profile', 'Create', 'Money', 'Rights', 'Grow', 'Help & account'].forEach((l) => assert.ok(js.includes('label: "' + l + '"'), l + ' group exists'));
assert.ok(!js.includes('label: "My music"') && !js.includes('label: "Publishing"'), 'old group names are gone');
assert.ok(!js.includes('top: true') && !js.includes('side-top-link'), 'no loose links outside a category');
assert.ok(js.includes('"Publishing setup"') && css.includes('a.side-lead'), 'Publishing setup is a secondary button atop Rights');
assert.ok(/SIDE_DROP = \["make-human", "battle"\]/.test(js), 'Make it human and Battle leave the menu');
assert.ok(read('song-helper.html').includes('href="/make-human"') && read('song-helper.html').includes('href="/battle"'), 'Song Lab links to Make it human and Battle');
assert.ok(!js.includes('SIDE_FREE') && !js.includes('side-free') && !css.includes('.side-free'), 'no Free or credit tags in the menu yet');
const menu = js.slice(js.indexOf('var SIDE_GROUPS'), js.indexOf('function setupAppMenu'));
assert.ok(menu.includes('box.hidden = true') && menu.includes('box.style.display') && menu.includes('aria-expanded", "false"'), 'every group starts collapsed');
assert.ok(!menu.includes('scrollIntoView'), 'opening a group does not scroll the menu');
assert.ok(menu.includes('ArrowDown') && menu.includes('ArrowUp') && menu.includes('Home') && menu.includes('End') && menu.includes('Escape'), 'headers move by keyboard');
assert.ok(css.includes('.side-more-list[hidden] { display: none !important; }') && css.includes('.side-group-panel[hidden]'), 'collapsed panels stay hidden');
assert.ok(css.includes('.side-group-toggle.is-current'), 'current page group is marked without opening');
assert.ok(read('my-roadmap.html').includes('destination.js') && read('my-roadmap.js').includes('aria-current="step"'), 'roadmap steps link to pages');
assert.ok(js.includes('side-group-toggle') && js.includes('aria-expanded'), 'group header is a toggle with aria-expanded');
assert.ok(js.includes('fetch("settings.html"'), 'flow menu reads its links from settings.html');
assert.ok(!js.includes('FLOW_SIDE_HTML'), 'no copied Settings link list');
assert.ok(css.includes('.side-group-chevron'), 'group chevron is styled');
assert.ok(js.includes('function setupFlowMenu'), 'release flow pages build the shared side menu');
assert.ok(js.includes('window.PLAI_FLOW_MENU_ONLY'), 'flow pages run site.js in menu-only mode');
assert.ok(css.includes('.side-more-toggle'), 'More toggle is styled');
assert.ok(/@media \(min-width: 981px\)[\s\S]*?\.app \.topbar \.menu-toggle \{ display: inline-flex; \}/.test(css), 'signed-in top bar menu button shows on desktop too');
['upload.html', 'attest.html', 'split-sheet.html', 'review.html', 'submitted.html'].forEach((f) => {
  const html = read(f);
  assert.ok(html.includes('window.PLAI_FLOW_MENU_ONLY = true'), f + ' turns on the flow menu');
  assert.ok(html.includes('site.js?v=20261024acc1'), f + ' loads site.js at the menu stamp');
  assert.ok(html.includes('site.css?v=20261023menu2'), f + ' cache-busts site.css at the menu stamp');
});
assert.ok(!/\u2014/.test(menu), 'no em dashes');
console.log('release-menu.test.js ok');
